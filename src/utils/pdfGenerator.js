/**
 * pdfGenerator.js — builds the downloadable/printable Prescription PDF.
 *
 * Uses jsPDF directly (no html2canvas) so the output is real vector text —
 * crisp at any zoom, small file size, and the text stays selectable/
 * searchable in the downloaded PDF. Run `npm install jspdf` if it isn't in
 * node_modules yet (already added to package.json).
 *
 * Usage:
 *   import { downloadPrescriptionPdf, printPrescriptionPdf } from "../../utils/pdfGenerator";
 *   downloadPrescriptionPdf(prescription, { patient, doctor });
 *   printPrescriptionPdf(prescription, { patient, doctor });
 */
import { jsPDF } from "jspdf";
import { formatDate } from "./helpers";

const PAGE_WIDTH = 210; // A4 mm
const PAGE_HEIGHT = 297;
const MARGIN = 15;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;
const FOOTER_Y = 285;

const COLOR_PRIMARY = [37, 99, 235]; // #2563EB
const COLOR_NAVY = [15, 23, 42]; // #0F172A
const COLOR_SECONDARY = [100, 116, 139]; // #64748B
const COLOR_MUTED = [148, 163, 184]; // #94A3B8
const COLOR_LINE = [226, 232, 240]; // slate-200
const COLOR_HEAD_BG = [239, 246, 255]; // #EFF6FF

function ensureSpace(doc, y, needed) {
  if (y + needed > FOOTER_Y - 5) {
    doc.addPage();
    return MARGIN;
  }
  return y;
}

function sectionTitle(doc, label, x, y) {
  y = ensureSpace(doc, y, 10);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(...COLOR_PRIMARY);
  doc.text(label.toUpperCase(), x, y);
  return y + 5;
}

function wrapText(doc, text, x, y, width = CONTENT_WIDTH) {
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10.5);
  doc.setTextColor(...COLOR_NAVY);
  const lines = doc.splitTextToSize(String(text), width);
  y = ensureSpace(doc, y, lines.length * 5 + 2);
  doc.text(lines, x, y);
  return y + lines.length * 5;
}

function drawKeyValueBlock(doc, rows, x, y, width) {
  let cursorY = y;
  rows.forEach(([label, value]) => {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(...COLOR_MUTED);
    doc.text(label.toUpperCase(), x, cursorY);
    cursorY += 4.2;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10.5);
    doc.setTextColor(...COLOR_NAVY);
    const lines = doc.splitTextToSize(String(value ?? "-"), width);
    doc.text(lines, x, cursorY);
    cursorY += lines.length * 4.6 + 2.5;
  });
  return cursorY;
}

function drawMedicinesTable(doc, medicines, x, y) {
  const columns = [
    { key: "name", label: "Medicine", width: 44 },
    { key: "dosage", label: "Dosage", width: 24 },
    { key: "frequency", label: "Frequency", width: 30 },
    { key: "duration", label: "Duration", width: 24 },
    { key: "instructions", label: "Instructions", width: CONTENT_WIDTH - (44 + 24 + 30 + 24) },
  ];

  const drawHeader = (headerY) => {
    doc.setFillColor(...COLOR_HEAD_BG);
    doc.rect(x, headerY, CONTENT_WIDTH, 8, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(...COLOR_PRIMARY);
    let cx = x + 2;
    columns.forEach((col) => {
      doc.text(col.label, cx, headerY + 5.5);
      cx += col.width;
    });
    return headerY + 8;
  };

  if (!medicines.length) {
    y = ensureSpace(doc, y, 16);
    y = drawHeader(y);
    doc.setFont("helvetica", "italic");
    doc.setFontSize(9.5);
    doc.setTextColor(...COLOR_SECONDARY);
    doc.text("No medicines listed on this prescription.", x + 2, y + 6);
    return y + 12;
  }

  y = ensureSpace(doc, y, 16);
  y = drawHeader(y);

  medicines.forEach((med) => {
    const cellLines = columns.map((col) =>
      doc.splitTextToSize(String(med[col.key] || "-"), col.width - 3)
    );
    const rowHeight = Math.max(...cellLines.map((l) => l.length)) * 4.4 + 4;

    y = ensureSpace(doc, y, rowHeight + 8);
    if (y === MARGIN) y = drawHeader(y); // re-draw header if we just paged

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9.5);
    doc.setTextColor(...COLOR_NAVY);
    let cx = x + 2;
    columns.forEach((col, i) => {
      doc.text(cellLines[i], cx, y + 5);
      cx += col.width;
    });
    doc.setDrawColor(...COLOR_LINE);
    doc.line(x, y + rowHeight, x + CONTENT_WIDTH, y + rowHeight);
    y += rowHeight;
  });

  return y + 4;
}

function drawFooter(doc) {
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setDrawColor(...COLOR_LINE);
    doc.line(MARGIN, FOOTER_Y, PAGE_WIDTH - MARGIN, FOOTER_Y);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(...COLOR_MUTED);
    doc.text("Generated by GLT Healthcare Admin Panel", MARGIN, FOOTER_Y + 5);
    doc.text(`Page ${i} of ${pageCount}`, PAGE_WIDTH - MARGIN, FOOTER_Y + 5, { align: "right" });
  }
}

function buildPrescriptionDoc(prescription, { patient, doctor } = {}) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });

  // Header band
  doc.setFillColor(...COLOR_PRIMARY);
  doc.rect(0, 0, PAGE_WIDTH, 26, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(17);
  doc.text("GLT Healthcare", MARGIN, 15);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9.5);
  doc.text("Prescription", MARGIN, 21.5);

  doc.setFontSize(9.5);
  doc.text(`Prescription #${prescription.id}`, PAGE_WIDTH - MARGIN, 15, { align: "right" });
  doc.text(`Date: ${formatDate(prescription.createdAt)}`, PAGE_WIDTH - MARGIN, 21.5, {
    align: "right",
  });

  let y = 36;
  const colWidth = CONTENT_WIDTH / 2;

  const patientRows = [
    ["Patient", patient?.name || "-"],
    ["Mobile", patient?.mobile || "-"],
    ["Age / Gender", `${patient?.age ?? "-"} / ${patient?.gender || "-"}`],
  ];
  const doctorRows = [
    ["Doctor", doctor?.name ? `Dr. ${doctor.name}` : "-"],
    ["Specialization", doctor?.specialization || "-"],
    ["Mobile", doctor?.mobile || "-"],
  ];

  const yAfterPatient = drawKeyValueBlock(doc, patientRows, MARGIN, y, colWidth - 6);
  const yAfterDoctor = drawKeyValueBlock(doc, doctorRows, MARGIN + colWidth, y, colWidth - 6);
  y = Math.max(yAfterPatient, yAfterDoctor) + 2;

  doc.setDrawColor(...COLOR_LINE);
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y);
  y += 8;

  y = sectionTitle(doc, "Medicines", MARGIN, y);
  y = drawMedicinesTable(doc, prescription.medicines || [], MARGIN, y);

  if (prescription.testsRecommended) {
    y = sectionTitle(doc, "Tests Recommended", MARGIN, y);
    y = wrapText(doc, prescription.testsRecommended, MARGIN, y);
    y += 4;
  }

  if (prescription.additionalAdvice) {
    y = sectionTitle(doc, "Additional Advice", MARGIN, y);
    y = wrapText(doc, prescription.additionalAdvice, MARGIN, y);
    y += 4;
  }

  if (prescription.followUpDate) {
    y = sectionTitle(doc, "Follow-up Date", MARGIN, y);
    y = wrapText(doc, formatDate(prescription.followUpDate), MARGIN, y);
  }

  drawFooter(doc);
  return doc;
}

function fileNameFor(prescription, patient) {
  const safeName = (patient?.name || "patient").replace(/[^a-z0-9]+/gi, "_");
  return `Prescription-${prescription.id}-${safeName}.pdf`;
}

/** Saves the prescription as a PDF file to the user's Downloads folder. */
export function downloadPrescriptionPdf(prescription, meta = {}) {
  const doc = buildPrescriptionDoc(prescription, meta);
  doc.save(fileNameFor(prescription, meta.patient));
}

/**
 * Opens the prescription PDF in a new tab and triggers the print dialog.
 * Auto-print is best-effort — some browsers block scripted print() on a
 * blob PDF viewer, in which case the user can still print from the tab
 * that opens (Ctrl/Cmd + P), so this never throws either way.
 */
export function printPrescriptionPdf(prescription, meta = {}) {
  const doc = buildPrescriptionDoc(prescription, meta);
  const blobUrl = doc.output("bloburl");
  const printWindow = window.open(blobUrl, "_blank");
  if (!printWindow) return;
  try {
    printWindow.addEventListener("load", () => {
      printWindow.focus();
      printWindow.print();
    });
  } catch {
    // Auto-print not permitted by the browser — the opened tab is enough.
  }
}

export default { downloadPrescriptionPdf, printPrescriptionPdf };